-- ============================================================
-- 1. OPERATOR VERIFICATIONS
-- ============================================================

CREATE TABLE operator_verifications (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                        user_id BIGINT NOT NULL,

                                        business_name VARCHAR(200),

                                        business_registration_number VARCHAR(100),

                                        verification_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                                        submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                        reviewed_by BIGINT,

                                        reviewed_at TIMESTAMPTZ,

                                        rejection_reason TEXT,

                                        notes TEXT,

                                        CONSTRAINT fk_operator_verifications_user
                                            FOREIGN KEY (user_id)
                                                REFERENCES users(id),

                                        CONSTRAINT fk_operator_verifications_reviewer
                                            FOREIGN KEY (reviewed_by)
                                                REFERENCES users(id),

                                        CONSTRAINT chk_operator_verification_status
                                            CHECK (
                                                verification_status IN (
                                                                        'PENDING',
                                                                        'UNDER_REVIEW',
                                                                        'VERIFIED',
                                                                        'REJECTED',
                                                                        'SUSPENDED'
                                                    )
                                                ),

                                        CONSTRAINT uq_operator_verification_user
                                            UNIQUE (user_id)
);


CREATE INDEX idx_operator_verifications_status
    ON operator_verifications(verification_status);

CREATE INDEX idx_operator_verifications_user
    ON operator_verifications(user_id);

CREATE INDEX idx_operator_verifications_reviewer
    ON operator_verifications(reviewed_by);


-- ============================================================
-- 2. AUDIT LOGS
-- ============================================================

CREATE TABLE audit_logs (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            user_id BIGINT,

                            action VARCHAR(100) NOT NULL,

                            entity_type VARCHAR(100) NOT NULL,

                            entity_id BIGINT,

                            description TEXT,

                            old_values JSONB,

                            new_values JSONB,

                            ip_address VARCHAR(45),

                            user_agent TEXT,

                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_audit_logs_user
                                FOREIGN KEY (user_id)
                                    REFERENCES users(id)
                                    ON DELETE SET NULL
);


CREATE INDEX idx_audit_logs_user
    ON audit_logs(user_id);

CREATE INDEX idx_audit_logs_action
    ON audit_logs(action);

CREATE INDEX idx_audit_logs_entity
    ON audit_logs(entity_type, entity_id);

CREATE INDEX idx_audit_logs_created_at
    ON audit_logs(created_at);