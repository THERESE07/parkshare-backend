-- ============================================================
-- PARKSHARE - V18
-- Operator VAT status, mobile-money fees, contact verification, OTP codes
-- ============================================================

-- 1. VAT only applies to operators an admin has verified as VAT-registered with RRA.
ALTER TABLE operator_verifications
    ADD COLUMN tin VARCHAR(9),
    ADD COLUMN vat_registered BOOLEAN NOT NULL DEFAULT FALSE,
    ADD CONSTRAINT chk_operator_tin CHECK (tin IS NULL OR tin ~ '^[0-9]{9}$');

-- 2. Fee charged by MTN MoMo / Airtel Money on each payment (deducted from the operator payout).
ALTER TABLE payments
    ADD COLUMN provider_fee NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    ADD CONSTRAINT chk_payment_provider_fee CHECK (provider_fee >= 0);

-- 3. Contact verification by one-time code.
ALTER TABLE users
    ADD COLUMN phone_verified_at TIMESTAMPTZ,
    ADD COLUMN email_verified_at TIMESTAMPTZ;

CREATE TABLE otp_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    destination VARCHAR(255) NOT NULL,
    channel VARCHAR(10) NOT NULL,
    purpose VARCHAR(30) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_otp_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_otp_channel CHECK (channel IN ('SMS', 'EMAIL')),
    CONSTRAINT chk_otp_purpose CHECK (purpose IN ('VERIFY_PHONE', 'VERIFY_EMAIL', 'RESET_PASSWORD')),
    CONSTRAINT chk_otp_attempts CHECK (attempts >= 0)
);

CREATE INDEX idx_otp_lookup ON otp_codes(destination, purpose, created_at);
