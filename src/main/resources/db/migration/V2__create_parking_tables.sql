-- ============================================================
-- PARKSHARE - V2
-- PARKING MANAGEMENT TABLES
-- ============================================================


-- ============================================================
-- 1. PARKING LOTS
-- ============================================================

CREATE TABLE parking_lots (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              operator_id BIGINT NOT NULL,

                              name VARCHAR(150) NOT NULL,
                              description TEXT,

                              address VARCHAR(255) NOT NULL,
                              district VARCHAR(100) NOT NULL,
                              city VARCHAR(100) NOT NULL DEFAULT 'Kigali',

                              latitude NUMERIC(10, 7),
                              longitude NUMERIC(10, 7),

                              status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                              total_capacity INTEGER NOT NULL DEFAULT 0,

                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_parking_lots_operator
                                  FOREIGN KEY (operator_id)
                                      REFERENCES users(id),

                              CONSTRAINT chk_parking_lots_status
                                  CHECK (
                                      status IN (
                                                 'PENDING',
                                                 'ACTIVE',
                                                 'INACTIVE',
                                                 'SUSPENDED'
                                          )
                                      ),

                              CONSTRAINT chk_parking_lots_capacity
                                  CHECK (total_capacity >= 0)
);


-- ============================================================
-- 2. PARKING ZONES
-- ============================================================

CREATE TABLE parking_zones (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               parking_lot_id BIGINT NOT NULL,

                               name VARCHAR(100) NOT NULL,
                               description TEXT,

                               capacity INTEGER NOT NULL DEFAULT 0,

                               status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_parking_zones_lot
                                   FOREIGN KEY (parking_lot_id)
                                       REFERENCES parking_lots(id)
                                       ON DELETE CASCADE,

                               CONSTRAINT chk_parking_zones_capacity
                                   CHECK (capacity >= 0),

                               CONSTRAINT chk_parking_zones_status
                                   CHECK (
                                       status IN (
                                                  'ACTIVE',
                                                  'INACTIVE'
                                           )
                                       ),

                               CONSTRAINT uq_parking_zone_name
                                   UNIQUE (parking_lot_id, name)
);


-- ============================================================
-- 3. PARKING SPACES
-- ============================================================

CREATE TABLE parking_spaces (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                parking_zone_id BIGINT NOT NULL,

                                space_number VARCHAR(50) NOT NULL,

                                space_type VARCHAR(30) NOT NULL DEFAULT 'STANDARD',

                                status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',

                                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_parking_spaces_zone
                                    FOREIGN KEY (parking_zone_id)
                                        REFERENCES parking_zones(id)
                                        ON DELETE CASCADE,

                                CONSTRAINT chk_parking_spaces_type
                                    CHECK (
                                        space_type IN (
                                                       'STANDARD',
                                                       'DISABLED',
                                                       'VIP',
                                                       'EV',
                                                       'MOTORCYCLE'
                                            )
                                        ),

                                CONSTRAINT chk_parking_spaces_status
                                    CHECK (
                                        status IN (
                                                   'AVAILABLE',
                                                   'OCCUPIED',
                                                   'RESERVED',
                                                   'MAINTENANCE',
                                                   'BLOCKED'
                                            )
                                        ),

                                CONSTRAINT uq_parking_space_number
                                    UNIQUE (parking_zone_id, space_number)
);


-- ============================================================
-- 4. PARKING FEATURES
-- ============================================================

CREATE TABLE parking_features (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  parking_lot_id BIGINT NOT NULL,

                                  feature_code VARCHAR(50) NOT NULL,

                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  CONSTRAINT fk_parking_features_lot
                                      FOREIGN KEY (parking_lot_id)
                                          REFERENCES parking_lots(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT uq_parking_feature
                                      UNIQUE (parking_lot_id, feature_code)
);


-- ============================================================
-- 5. PARKING OPERATING HOURS
-- ============================================================

CREATE TABLE parking_operating_hours (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                         parking_lot_id BIGINT NOT NULL,

                                         day_of_week VARCHAR(15) NOT NULL,

                                         opening_time TIME,
                                         closing_time TIME,

                                         is_closed BOOLEAN NOT NULL DEFAULT FALSE,

                                         CONSTRAINT fk_parking_hours_lot
                                             FOREIGN KEY (parking_lot_id)
                                                 REFERENCES parking_lots(id)
                                                 ON DELETE CASCADE,

                                         CONSTRAINT chk_parking_hours_day
                                             CHECK (
                                                 day_of_week IN (
                                                                 'MONDAY',
                                                                 'TUESDAY',
                                                                 'WEDNESDAY',
                                                                 'THURSDAY',
                                                                 'FRIDAY',
                                                                 'SATURDAY',
                                                                 'SUNDAY'
                                                     )
                                                 ),

                                         CONSTRAINT uq_parking_hours_day
                                             UNIQUE (parking_lot_id, day_of_week)
);


-- ============================================================
-- 6. PARKING VERIFICATIONS
-- ============================================================

CREATE TABLE parking_verifications (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       parking_lot_id BIGINT NOT NULL,

                                       verified_by BIGINT,

                                       verification_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                                       verification_method VARCHAR(50),

                                       notes TEXT,

                                       verified_at TIMESTAMPTZ,

                                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       CONSTRAINT fk_parking_verifications_lot
                                           FOREIGN KEY (parking_lot_id)
                                               REFERENCES parking_lots(id)
                                               ON DELETE CASCADE,

                                       CONSTRAINT fk_parking_verifications_user
                                           FOREIGN KEY (verified_by)
                                               REFERENCES users(id),

                                       CONSTRAINT chk_parking_verification_status
                                           CHECK (
                                               verification_status IN (
                                                                       'PENDING',
                                                                       'VERIFIED',
                                                                       'REJECTED',
                                                                       'EXPIRED'
                                                   )
                                               )
);


-- ============================================================
-- 7. PARKING LOT STAFF
-- ============================================================

CREATE TABLE parking_lot_staff (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   parking_lot_id BIGINT NOT NULL,

                                   user_id BIGINT NOT NULL,

                                   assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   active BOOLEAN NOT NULL DEFAULT TRUE,

                                   CONSTRAINT fk_parking_lot_staff_lot
                                       FOREIGN KEY (parking_lot_id)
                                           REFERENCES parking_lots(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT fk_parking_lot_staff_user
                                       FOREIGN KEY (user_id)
                                           REFERENCES users(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT uq_parking_lot_staff
                                       UNIQUE (parking_lot_id, user_id)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_parking_lots_operator
    ON parking_lots(operator_id);

CREATE INDEX idx_parking_lots_status
    ON parking_lots(status);

CREATE INDEX idx_parking_lots_location
    ON parking_lots(latitude, longitude);

CREATE INDEX idx_parking_zones_lot
    ON parking_zones(parking_lot_id);

CREATE INDEX idx_parking_spaces_zone
    ON parking_spaces(parking_zone_id);

CREATE INDEX idx_parking_spaces_status
    ON parking_spaces(status);

CREATE INDEX idx_parking_verifications_lot
    ON parking_verifications(parking_lot_id);

CREATE INDEX idx_parking_lot_staff_user
    ON parking_lot_staff(user_id);