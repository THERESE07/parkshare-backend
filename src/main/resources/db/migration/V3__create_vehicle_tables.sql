-- VEHICLE MANAGEMENT
-- ============================================================


CREATE TABLE vehicles (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          user_id BIGINT NOT NULL,

                          plate_number VARCHAR(30) NOT NULL,
                          vehicle_type VARCHAR(30) NOT NULL DEFAULT 'CAR',

                          make VARCHAR(100),
                          model VARCHAR(100),
                          color VARCHAR(50),

                          is_default BOOLEAN NOT NULL DEFAULT FALSE,
                          is_active BOOLEAN NOT NULL DEFAULT TRUE,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_vehicles_user
                              FOREIGN KEY (user_id)
                                  REFERENCES users(id)
                                  ON DELETE CASCADE,

                          CONSTRAINT uq_vehicle_plate
                              UNIQUE (plate_number),

                          CONSTRAINT chk_vehicle_type
                              CHECK (
                                  vehicle_type IN (
                                                   'CAR',
                                                   'MOTORCYCLE',
                                                   'TRUCK',
                                                   'BUS',
                                                   'OTHER'
                                      )
                                  )
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_vehicles_user
    ON vehicles(user_id);

CREATE INDEX idx_vehicles_plate
    ON vehicles(plate_number);

CREATE INDEX idx_vehicles_active
    ON vehicles(is_active);