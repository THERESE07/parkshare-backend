-- ============================================================
-- 1. RESERVATIONS
-- ============================================================

CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              user_id BIGINT NOT NULL,
                              vehicle_id BIGINT NOT NULL,
                              parking_lot_id BIGINT NOT NULL,
                              parking_space_id BIGINT,

                              reservation_code VARCHAR(50) NOT NULL,

                              start_time TIMESTAMPTZ NOT NULL,
                              end_time TIMESTAMPTZ NOT NULL,

                              status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                              total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
                              currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                              notes TEXT,

                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_reservations_user
                                  FOREIGN KEY (user_id)
                                      REFERENCES users(id),

                              CONSTRAINT fk_reservations_vehicle
                                  FOREIGN KEY (vehicle_id)
                                      REFERENCES vehicles(id),

                              CONSTRAINT fk_reservations_parking_lot
                                  FOREIGN KEY (parking_lot_id)
                                      REFERENCES parking_lots(id),

                              CONSTRAINT fk_reservations_parking_space
                                  FOREIGN KEY (parking_space_id)
                                      REFERENCES parking_spaces(id),

                              CONSTRAINT uq_reservation_code
                                  UNIQUE (reservation_code),

                              CONSTRAINT chk_reservation_status
                                  CHECK (
                                      status IN (
                                                 'PENDING',
                                                 'CONFIRMED',
                                                 'CANCELLED',
                                                 'EXPIRED',
                                                 'CHECKED_IN',
                                                 'COMPLETED',
                                                 'NO_SHOW'
                                          )
                                      ),

                              CONSTRAINT chk_reservation_time
                                  CHECK (end_time > start_time),

                              CONSTRAINT chk_reservation_amount
                                  CHECK (total_amount >= 0),

                              CONSTRAINT chk_reservation_currency
                                  CHECK (currency = 'RWF')
);


-- ============================================================
-- 2. RESERVATION STATUS HISTORY
-- ============================================================

CREATE TABLE reservation_status_history (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                            reservation_id BIGINT NOT NULL,

                                            old_status VARCHAR(30),
                                            new_status VARCHAR(30) NOT NULL,

                                            changed_by BIGINT,

                                            reason TEXT,

                                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                            CONSTRAINT fk_reservation_history_reservation
                                                FOREIGN KEY (reservation_id)
                                                    REFERENCES reservations(id)
                                                    ON DELETE CASCADE,

                                            CONSTRAINT fk_reservation_history_user
                                                FOREIGN KEY (changed_by)
                                                    REFERENCES users(id)
);


-- ============================================================
-- 3. RESERVATION QR CODES
-- ============================================================

CREATE TABLE reservation_qr_codes (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                      reservation_id BIGINT NOT NULL,

                                      token_hash VARCHAR(255) NOT NULL,

                                      expires_at TIMESTAMPTZ NOT NULL,

                                      used_at TIMESTAMPTZ,

                                      is_active BOOLEAN NOT NULL DEFAULT TRUE,

                                      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT fk_reservation_qr_reservation
                                          FOREIGN KEY (reservation_id)
                                              REFERENCES reservations(id)
                                              ON DELETE CASCADE,

                                      CONSTRAINT uq_reservation_qr_token
                                          UNIQUE (token_hash)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_reservations_user
    ON reservations(user_id);

CREATE INDEX idx_reservations_vehicle
    ON reservations(vehicle_id);

CREATE INDEX idx_reservations_parking_lot
    ON reservations(parking_lot_id);

CREATE INDEX idx_reservations_parking_space
    ON reservations(parking_space_id);

CREATE INDEX idx_reservations_status
    ON reservations(status);

CREATE INDEX idx_reservations_start_time
    ON reservations(start_time);

CREATE INDEX idx_reservations_end_time
    ON reservations(end_time);

CREATE INDEX idx_reservation_history_reservation
    ON reservation_status_history(reservation_id);

CREATE INDEX idx_reservation_qr_reservation
    ON reservation_qr_codes(reservation_id);