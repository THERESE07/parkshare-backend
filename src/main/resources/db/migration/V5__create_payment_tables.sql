-- PAYMENT MANAGEMENT
-- ============================================================


-- ============================================================
-- 1. PAYMENTS
-- ============================================================

CREATE TABLE payments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          reservation_id BIGINT NOT NULL,

                          amount NUMERIC(12, 2) NOT NULL,
                          currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                          payment_method VARCHAR(30) NOT NULL,

                          status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                          paid_at TIMESTAMPTZ,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_payments_reservation
                              FOREIGN KEY (reservation_id)
                                  REFERENCES reservations(id),

                          CONSTRAINT uq_payment_reservation
                              UNIQUE (reservation_id),

                          CONSTRAINT chk_payment_amount
                              CHECK (amount >= 0),

                          CONSTRAINT chk_payment_currency
                              CHECK (currency = 'RWF'),

                          CONSTRAINT chk_payment_method
                              CHECK (
                                  payment_method IN (
                                                     'MTN_MOMO',
                                                     'AIRTEL_MONEY',
                                                     'CARD',
                                                     'CASH'
                                      )
                                  ),

                          CONSTRAINT chk_payment_status
                              CHECK (
                                  status IN (
                                             'PENDING',
                                             'PROCESSING',
                                             'SUCCESS',
                                             'FAILED',
                                             'CANCELLED',
                                             'REFUNDED'
                                      )
                                  )
);


-- ============================================================
-- 2. PAYMENT TRANSACTIONS
-- ============================================================

CREATE TABLE payment_transactions (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                      payment_id BIGINT NOT NULL,

                                      provider VARCHAR(50) NOT NULL,

                                      provider_transaction_id VARCHAR(255),

                                      transaction_reference VARCHAR(100) NOT NULL,

                                      amount NUMERIC(12, 2) NOT NULL,
                                      currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                                      status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                                      failure_reason TEXT,

                                      initiated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      completed_at TIMESTAMPTZ,

                                      CONSTRAINT fk_payment_transactions_payment
                                          FOREIGN KEY (payment_id)
                                              REFERENCES payments(id)
                                              ON DELETE CASCADE,

                                      CONSTRAINT uq_payment_transaction_reference
                                          UNIQUE (transaction_reference),

                                      CONSTRAINT chk_payment_transaction_amount
                                          CHECK (amount >= 0),

                                      CONSTRAINT chk_payment_transaction_currency
                                          CHECK (currency = 'RWF'),

                                      CONSTRAINT chk_payment_transaction_status
                                          CHECK (
                                              status IN (
                                                         'PENDING',
                                                         'PROCESSING',
                                                         'SUCCESS',
                                                         'FAILED',
                                                         'CANCELLED'
                                                  )
                                              )
);


-- ============================================================
-- 3. PAYMENT WEBHOOKS
-- ============================================================

CREATE TABLE payment_webhooks (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  provider VARCHAR(50) NOT NULL,

                                  event_id VARCHAR(255) NOT NULL,

                                  event_type VARCHAR(100),

                                  payload JSONB NOT NULL,

                                  processed BOOLEAN NOT NULL DEFAULT FALSE,

                                  processed_at TIMESTAMPTZ,

                                  received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  CONSTRAINT uq_payment_webhook_event
                                      UNIQUE (provider, event_id)
);


-- ============================================================
-- 4. REFUNDS
-- ============================================================

CREATE TABLE refunds (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         payment_id BIGINT NOT NULL,

                         amount NUMERIC(12, 2) NOT NULL,

                         currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                         reason TEXT,

                         status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                         provider_refund_id VARCHAR(255),

                         requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         completed_at TIMESTAMPTZ,

                         CONSTRAINT fk_refunds_payment
                             FOREIGN KEY (payment_id)
                                 REFERENCES payments(id),

                         CONSTRAINT chk_refund_amount
                             CHECK (amount > 0),

                         CONSTRAINT chk_refund_currency
                             CHECK (currency = 'RWF'),

                         CONSTRAINT chk_refund_status
                             CHECK (
                                 status IN (
                                            'PENDING',
                                            'PROCESSING',
                                            'SUCCESS',
                                            'FAILED',
                                            'CANCELLED'
                                     )
                                 )
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_payments_reservation
    ON payments(reservation_id);

CREATE INDEX idx_payments_status
    ON payments(status);

CREATE INDEX idx_payment_transactions_payment
    ON payment_transactions(payment_id);

CREATE INDEX idx_payment_transactions_provider
    ON payment_transactions(provider);

CREATE INDEX idx_payment_transactions_status
    ON payment_transactions(status);

CREATE INDEX idx_payment_webhooks_provider
    ON payment_webhooks(provider);

CREATE INDEX idx_payment_webhooks_processed
    ON payment_webhooks(processed);

CREATE INDEX idx_refunds_payment
    ON refunds(payment_id);

CREATE INDEX idx_refunds_status
    ON refunds(status);