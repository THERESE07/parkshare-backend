-- ============================================================
-- 1. CHECK-INS
-- ============================================================

CREATE TABLE check_ins (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           reservation_id BIGINT NOT NULL,

                           vehicle_id BIGINT NOT NULL,

                           parking_space_id BIGINT,

                           checked_in_by BIGINT,

                           check_in_method VARCHAR(30) NOT NULL DEFAULT 'QR',

                           checked_in_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           notes TEXT,

                           CONSTRAINT fk_check_ins_reservation
                               FOREIGN KEY (reservation_id)
                                   REFERENCES reservations(id),

                           CONSTRAINT fk_check_ins_vehicle
                               FOREIGN KEY (vehicle_id)
                                   REFERENCES vehicles(id),

                           CONSTRAINT fk_check_ins_space
                               FOREIGN KEY (parking_space_id)
                                   REFERENCES parking_spaces(id),

                           CONSTRAINT fk_check_ins_user
                               FOREIGN KEY (checked_in_by)
                                   REFERENCES users(id),

                           CONSTRAINT chk_check_in_method
                               CHECK (
                                   check_in_method IN (
                                                       'QR',
                                                       'CODE',
                                                       'MANUAL'
                                       )
                                   ),

                           CONSTRAINT uq_check_in_reservation
                               UNIQUE (reservation_id)
);


-- ============================================================
-- 2. CHECK-OUTS
-- ============================================================

CREATE TABLE check_outs (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            check_in_id BIGINT NOT NULL,

                            reservation_id BIGINT NOT NULL,

                            checked_out_by BIGINT,

                            check_out_method VARCHAR(30) NOT NULL DEFAULT 'QR',

                            checked_out_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            notes TEXT,

                            CONSTRAINT fk_check_outs_check_in
                                FOREIGN KEY (check_in_id)
                                    REFERENCES check_ins(id),

                            CONSTRAINT fk_check_outs_reservation
                                FOREIGN KEY (reservation_id)
                                    REFERENCES reservations(id),

                            CONSTRAINT fk_check_outs_user
                                FOREIGN KEY (checked_out_by)
                                    REFERENCES users(id),

                            CONSTRAINT chk_check_out_method
                                CHECK (
                                    check_out_method IN (
                                                         'QR',
                                                         'CODE',
                                                         'MANUAL'
                                        )
                                    ),

                            CONSTRAINT uq_check_out_check_in
                                UNIQUE (check_in_id)
);


-- ============================================================
-- 3. OCCUPANCY RECORDS
-- ============================================================

CREATE TABLE occupancy_records (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   parking_lot_id BIGINT NOT NULL,

                                   parking_zone_id BIGINT,

                                   total_capacity INTEGER NOT NULL,

                                   occupied_spaces INTEGER NOT NULL DEFAULT 0,

                                   reserved_spaces INTEGER NOT NULL DEFAULT 0,

                                   available_spaces INTEGER NOT NULL DEFAULT 0,

                                   source VARCHAR(30) NOT NULL DEFAULT 'SYSTEM',

                                   recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   CONSTRAINT fk_occupancy_lot
                                       FOREIGN KEY (parking_lot_id)
                                           REFERENCES parking_lots(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT fk_occupancy_zone
                                       FOREIGN KEY (parking_zone_id)
                                           REFERENCES parking_zones(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT chk_occupancy_capacity
                                       CHECK (total_capacity >= 0),

                                   CONSTRAINT chk_occupancy_occupied
                                       CHECK (occupied_spaces >= 0),

                                   CONSTRAINT chk_occupancy_reserved
                                       CHECK (reserved_spaces >= 0),

                                   CONSTRAINT chk_occupancy_available
                                       CHECK (available_spaces >= 0),

                                   CONSTRAINT chk_occupancy_source
                                       CHECK (
                                           source IN (
                                                      'SYSTEM',
                                                      'ATTENDANT',
                                                      'OPERATOR',
                                                      'SENSOR'
                                               )
                                           )
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_check_ins_reservation
    ON check_ins(reservation_id);

CREATE INDEX idx_check_ins_vehicle
    ON check_ins(vehicle_id);

CREATE INDEX idx_check_ins_space
    ON check_ins(parking_space_id);

CREATE INDEX idx_check_ins_checked_in_at
    ON check_ins(checked_in_at);

CREATE INDEX idx_check_outs_reservation
    ON check_outs(reservation_id);

CREATE INDEX idx_check_outs_checked_out_at
    ON check_outs(checked_out_at);

CREATE INDEX idx_occupancy_lot
    ON occupancy_records(parking_lot_id);

CREATE INDEX idx_occupancy_zone
    ON occupancy_records(parking_zone_id);

CREATE INDEX idx_occupancy_recorded_at
    ON occupancy_records(recorded_at);