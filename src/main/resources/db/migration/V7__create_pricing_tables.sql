-- ============================================================
-- 1. PRICING RULES
-- ============================================================

CREATE TABLE pricing_rules (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               parking_lot_id BIGINT NOT NULL,

                               name VARCHAR(100) NOT NULL,

                               pricing_type VARCHAR(30) NOT NULL,

                               amount NUMERIC(12, 2) NOT NULL,

                               currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                               minimum_duration_minutes INTEGER,

                               maximum_duration_minutes INTEGER,

                               active BOOLEAN NOT NULL DEFAULT TRUE,

                               effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               effective_until TIMESTAMPTZ,

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_pricing_rules_lot
                                   FOREIGN KEY (parking_lot_id)
                                       REFERENCES parking_lots(id)
                                       ON DELETE CASCADE,

                               CONSTRAINT chk_pricing_type
                                   CHECK (
                                       pricing_type IN (
                                                        'HOURLY',
                                                        'DAILY',
                                                        'FLAT'
                                           )
                                       ),

                               CONSTRAINT chk_pricing_amount
                                   CHECK (amount >= 0),

                               CONSTRAINT chk_pricing_currency
                                   CHECK (currency = 'RWF'),

                               CONSTRAINT chk_pricing_min_duration
                                   CHECK (
                                       minimum_duration_minutes IS NULL
                                           OR minimum_duration_minutes > 0
                                       ),

                               CONSTRAINT chk_pricing_max_duration
                                   CHECK (
                                       maximum_duration_minutes IS NULL
                                           OR maximum_duration_minutes > 0
                                       ),

                               CONSTRAINT chk_pricing_duration_range
                                   CHECK (
                                       maximum_duration_minutes IS NULL
                                           OR minimum_duration_minutes IS NULL
                                           OR maximum_duration_minutes >= minimum_duration_minutes
                                       ),

                               CONSTRAINT chk_pricing_effective_period
                                   CHECK (
                                       effective_until IS NULL
                                           OR effective_until > effective_from
                                       )
);


-- ============================================================
-- 2. SPECIAL RATES
-- ============================================================

CREATE TABLE special_rates (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               parking_lot_id BIGINT NOT NULL,

                               name VARCHAR(100) NOT NULL,

                               rate_type VARCHAR(30) NOT NULL,

                               amount NUMERIC(12, 2) NOT NULL,

                               currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                               start_time TIME,

                               end_time TIME,

                               start_date TIMESTAMPTZ,

                               end_date TIMESTAMPTZ,

                               active BOOLEAN NOT NULL DEFAULT TRUE,

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_special_rates_lot
                                   FOREIGN KEY (parking_lot_id)
                                       REFERENCES parking_lots(id)
                                       ON DELETE CASCADE,

                               CONSTRAINT chk_special_rate_type
                                   CHECK (
                                       rate_type IN (
                                                     'PEAK',
                                                     'OFF_PEAK',
                                                     'WEEKEND',
                                                     'HOLIDAY',
                                                     'EVENT'
                                           )
                                       ),

                               CONSTRAINT chk_special_rate_amount
                                   CHECK (amount >= 0),

                               CONSTRAINT chk_special_rate_currency
                                   CHECK (currency = 'RWF'),

                               CONSTRAINT chk_special_rate_time
                                   CHECK (
                                       end_time IS NULL
                                           OR start_time IS NULL
                                           OR end_time <> start_time
                                       ),

                               CONSTRAINT chk_special_rate_dates
                                   CHECK (
                                       end_date IS NULL
                                           OR start_date IS NULL
                                           OR end_date > start_date
                                       )
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_pricing_rules_lot
    ON pricing_rules(parking_lot_id);

CREATE INDEX idx_pricing_rules_active
    ON pricing_rules(active);

CREATE INDEX idx_pricing_rules_effective_from
    ON pricing_rules(effective_from);

CREATE INDEX idx_special_rates_lot
    ON special_rates(parking_lot_id);

CREATE INDEX idx_special_rates_active
    ON special_rates(active);

CREATE INDEX idx_special_rates_type
    ON special_rates(rate_type);