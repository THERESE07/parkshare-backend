-- ============================================================
-- 1. EVENTS
-- ============================================================

CREATE TABLE events (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        organizer_id BIGINT NOT NULL,

                        name VARCHAR(200) NOT NULL,

                        description TEXT,

                        venue_name VARCHAR(200),

                        address VARCHAR(255),

                        latitude NUMERIC(10, 7),
                        longitude NUMERIC(10, 7),

                        start_time TIMESTAMPTZ NOT NULL,
                        end_time TIMESTAMPTZ NOT NULL,

                        status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',

                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT fk_events_organizer
                            FOREIGN KEY (organizer_id)
                                REFERENCES users(id),

                        CONSTRAINT chk_event_time
                            CHECK (end_time > start_time),

                        CONSTRAINT chk_event_status
                            CHECK (
                                status IN (
                                           'DRAFT',
                                           'PUBLISHED',
                                           'ACTIVE',
                                           'COMPLETED',
                                           'CANCELLED'
                                    )
                                )
);


-- ============================================================
-- 2. EVENT PARKING ZONES
-- ============================================================

CREATE TABLE event_parking_zones (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     event_id BIGINT NOT NULL,

                                     parking_lot_id BIGINT NOT NULL,

                                     capacity INTEGER NOT NULL,

                                     reserved_count INTEGER NOT NULL DEFAULT 0,

                                     occupied_count INTEGER NOT NULL DEFAULT 0,

                                     available_count INTEGER NOT NULL DEFAULT 0,

                                     price NUMERIC(12, 2) NOT NULL DEFAULT 0.00,

                                     currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                                     status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',

                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_event_zones_event
                                         FOREIGN KEY (event_id)
                                             REFERENCES events(id)
                                             ON DELETE CASCADE,

                                     CONSTRAINT fk_event_zones_parking_lot
                                         FOREIGN KEY (parking_lot_id)
                                             REFERENCES parking_lots(id),

                                     CONSTRAINT chk_event_zone_capacity
                                         CHECK (capacity >= 0),

                                     CONSTRAINT chk_event_zone_reserved
                                         CHECK (reserved_count >= 0),

                                     CONSTRAINT chk_event_zone_occupied
                                         CHECK (occupied_count >= 0),

                                     CONSTRAINT chk_event_zone_available
                                         CHECK (available_count >= 0),

                                     CONSTRAINT chk_event_zone_price
                                         CHECK (price >= 0),

                                     CONSTRAINT chk_event_zone_currency
                                         CHECK (currency = 'RWF'),

                                     CONSTRAINT chk_event_zone_status
                                         CHECK (
                                             status IN (
                                                        'ACTIVE',
                                                        'INACTIVE',
                                                        'FULL'
                                                 )
                                             ),

                                     CONSTRAINT uq_event_parking_lot
                                         UNIQUE (event_id, parking_lot_id)
);


-- ============================================================
-- 3. EVENT RESERVATIONS
-- ============================================================

CREATE TABLE event_reservations (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    event_id BIGINT NOT NULL,

                                    event_parking_zone_id BIGINT NOT NULL,

                                    reservation_id BIGINT NOT NULL,

                                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_event_reservations_event
                                        FOREIGN KEY (event_id)
                                            REFERENCES events(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT fk_event_reservations_zone
                                        FOREIGN KEY (event_parking_zone_id)
                                            REFERENCES event_parking_zones(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT fk_event_reservations_reservation
                                        FOREIGN KEY (reservation_id)
                                            REFERENCES reservations(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT uq_event_reservation
                                        UNIQUE (event_id, reservation_id)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_events_organizer
    ON events(organizer_id);

CREATE INDEX idx_events_status
    ON events(status);

CREATE INDEX idx_events_start_time
    ON events(start_time);

CREATE INDEX idx_events_end_time
    ON events(end_time);

CREATE INDEX idx_event_zones_event
    ON event_parking_zones(event_id);

CREATE INDEX idx_event_zones_parking_lot
    ON event_parking_zones(parking_lot_id);

CREATE INDEX idx_event_zones_status
    ON event_parking_zones(status);

CREATE INDEX idx_event_reservations_event
    ON event_reservations(event_id);

CREATE INDEX idx_event_reservations_zone
    ON event_reservations(event_parking_zone_id);

CREATE INDEX idx_event_reservations_reservation
    ON event_reservations(reservation_id);