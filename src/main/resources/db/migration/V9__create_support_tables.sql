-- ============================================================
-- 1. REVIEWS
-- ============================================================

CREATE TABLE reviews (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         user_id BIGINT NOT NULL,

                         parking_lot_id BIGINT NOT NULL,

                         reservation_id BIGINT,

                         rating INTEGER NOT NULL,

                         comment TEXT,

                         created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT fk_reviews_user
                             FOREIGN KEY (user_id)
                                 REFERENCES users(id),

                         CONSTRAINT fk_reviews_parking_lot
                             FOREIGN KEY (parking_lot_id)
                                 REFERENCES parking_lots(id),

                         CONSTRAINT fk_reviews_reservation
                             FOREIGN KEY (reservation_id)
                                 REFERENCES reservations(id)
                                 ON DELETE SET NULL,

                         CONSTRAINT chk_reviews_rating
                             CHECK (rating BETWEEN 1 AND 5),

                         CONSTRAINT uq_review_reservation_user
                             UNIQUE (user_id, reservation_id)
);


CREATE INDEX idx_reviews_user
    ON reviews(user_id);

CREATE INDEX idx_reviews_parking_lot
    ON reviews(parking_lot_id);

CREATE INDEX idx_reviews_rating
    ON reviews(rating);


-- ============================================================
-- 2. ISSUE REPORTS
-- ============================================================

CREATE TABLE issue_reports (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               user_id BIGINT NOT NULL,

                               parking_lot_id BIGINT,

                               reservation_id BIGINT,

                               issue_type VARCHAR(50) NOT NULL,

                               title VARCHAR(200) NOT NULL,

                               description TEXT NOT NULL,

                               status VARCHAR(30) NOT NULL DEFAULT 'OPEN',

                               priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',

                               resolved_by BIGINT,

                               resolved_at TIMESTAMPTZ,

                               resolution_notes TEXT,

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_issue_reports_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES users(id),

                               CONSTRAINT fk_issue_reports_parking_lot
                                   FOREIGN KEY (parking_lot_id)
                                       REFERENCES parking_lots(id),

                               CONSTRAINT fk_issue_reports_reservation
                                   FOREIGN KEY (reservation_id)
                                       REFERENCES reservations(id)
                                       ON DELETE SET NULL,

                               CONSTRAINT fk_issue_reports_resolved_by
                                   FOREIGN KEY (resolved_by)
                                       REFERENCES users(id),

                               CONSTRAINT chk_issue_type
                                   CHECK (
                                       issue_type IN (
                                                      'PARKING_UNAVAILABLE',
                                                      'WRONG_AVAILABILITY',
                                                      'PAYMENT_PROBLEM',
                                                      'RESERVATION_PROBLEM',
                                                      'QR_PROBLEM',
                                                      'CHECK_IN_PROBLEM',
                                                      'CHECK_OUT_PROBLEM',
                                                      'OVERCHARGED',
                                                      'SAFETY',
                                                      'OTHER'
                                           )
                                       ),

                               CONSTRAINT chk_issue_status
                                   CHECK (
                                       status IN (
                                                  'OPEN',
                                                  'IN_PROGRESS',
                                                  'RESOLVED',
                                                  'CLOSED'
                                           )
                                       ),

                               CONSTRAINT chk_issue_priority
                                   CHECK (
                                       priority IN (
                                                    'LOW',
                                                    'MEDIUM',
                                                    'HIGH',
                                                    'URGENT'
                                           )
                                       )
);


CREATE INDEX idx_issue_reports_user
    ON issue_reports(user_id);

CREATE INDEX idx_issue_reports_parking_lot
    ON issue_reports(parking_lot_id);

CREATE INDEX idx_issue_reports_reservation
    ON issue_reports(reservation_id);

CREATE INDEX idx_issue_reports_status
    ON issue_reports(status);

CREATE INDEX idx_issue_reports_priority
    ON issue_reports(priority);


-- ============================================================
-- 3. SUPPORT TICKETS
-- ============================================================

CREATE TABLE support_tickets (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 user_id BIGINT NOT NULL,

                                 ticket_number VARCHAR(50) NOT NULL,

                                 subject VARCHAR(200) NOT NULL,

                                 description TEXT NOT NULL,

                                 category VARCHAR(50) NOT NULL DEFAULT 'GENERAL',

                                 status VARCHAR(30) NOT NULL DEFAULT 'OPEN',

                                 priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',

                                 assigned_to BIGINT,

                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 resolved_at TIMESTAMPTZ,

                                 CONSTRAINT fk_support_tickets_user
                                     FOREIGN KEY (user_id)
                                         REFERENCES users(id),

                                 CONSTRAINT fk_support_tickets_assigned_to
                                     FOREIGN KEY (assigned_to)
                                         REFERENCES users(id),

                                 CONSTRAINT uq_support_ticket_number
                                     UNIQUE (ticket_number),

                                 CONSTRAINT chk_support_category
                                     CHECK (
                                         category IN (
                                                      'GENERAL',
                                                      'ACCOUNT',
                                                      'PARKING',
                                                      'RESERVATION',
                                                      'PAYMENT',
                                                      'TECHNICAL',
                                                      'REFUND',
                                                      'OTHER'
                                             )
                                         ),

                                 CONSTRAINT chk_support_status
                                     CHECK (
                                         status IN (
                                                    'OPEN',
                                                    'IN_PROGRESS',
                                                    'WAITING_FOR_USER',
                                                    'RESOLVED',
                                                    'CLOSED'
                                             )
                                         ),

                                 CONSTRAINT chk_support_priority
                                     CHECK (
                                         priority IN (
                                                      'LOW',
                                                      'MEDIUM',
                                                      'HIGH',
                                                      'URGENT'
                                             )
                                         )
);


CREATE INDEX idx_support_tickets_user
    ON support_tickets(user_id);

CREATE INDEX idx_support_tickets_assigned_to
    ON support_tickets(assigned_to);

CREATE INDEX idx_support_tickets_status
    ON support_tickets(status);

CREATE INDEX idx_support_tickets_priority
    ON support_tickets(priority);


-- ============================================================
-- 4. DISPUTES
-- ============================================================

CREATE TABLE disputes (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          reservation_id BIGINT NOT NULL,

                          raised_by BIGINT NOT NULL,

                          assigned_to BIGINT,

                          dispute_type VARCHAR(50) NOT NULL,

                          description TEXT NOT NULL,

                          amount_disputed NUMERIC(12, 2) NOT NULL DEFAULT 0.00,

                          currency VARCHAR(3) NOT NULL DEFAULT 'RWF',

                          status VARCHAR(30) NOT NULL DEFAULT 'OPEN',

                          resolution TEXT,

                          resolved_at TIMESTAMPTZ,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_disputes_reservation
                              FOREIGN KEY (reservation_id)
                                  REFERENCES reservations(id),

                          CONSTRAINT fk_disputes_raised_by
                              FOREIGN KEY (raised_by)
                                  REFERENCES users(id),

                          CONSTRAINT fk_disputes_assigned_to
                              FOREIGN KEY (assigned_to)
                                  REFERENCES users(id),

                          CONSTRAINT chk_dispute_type
                              CHECK (
                                  dispute_type IN (
                                                   'PAYMENT',
                                                   'REFUND',
                                                   'OVERCHARGE',
                                                   'RESERVATION',
                                                   'SERVICE',
                                                   'DAMAGE',
                                                   'OTHER'
                                      )
                                  ),

                          CONSTRAINT chk_dispute_amount
                              CHECK (amount_disputed >= 0),

                          CONSTRAINT chk_dispute_currency
                              CHECK (currency = 'RWF'),

                          CONSTRAINT chk_dispute_status
                              CHECK (
                                  status IN (
                                             'OPEN',
                                             'UNDER_REVIEW',
                                             'RESOLVED',
                                             'REJECTED',
                                             'CLOSED'
                                      )
                                  )
);


CREATE INDEX idx_disputes_reservation
    ON disputes(reservation_id);

CREATE INDEX idx_disputes_raised_by
    ON disputes(raised_by);

CREATE INDEX idx_disputes_assigned_to
    ON disputes(assigned_to);

CREATE INDEX idx_disputes_status
    ON disputes(status);